const FILE_HEADER = '// @ts-nocheck\n/* eslint-disable */\n// Generated by `fexport convert generate`. Safe to edit by hand.\n';

const exists = (p: string): Promise<boolean> => stat(p).then(() => true, () => false);

async function readJson<T>(file: string, fallback: T): Promise<T> {
  try {
    return JSON.parse(await readFile(file, 'utf8')) as T;
  } catch {
    return fallback;
  }
}

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** Inserts the generated imports and view body into a scaffolded page file; safe to run again. */
export function patchPage(source: string, imports: string, body: string): string {
  const importBlock = `// fexport:imports-start\n${imports}\n// fexport:imports-end\n`;
  const bodyBlock = `/* fexport:body-start */\n  ${body}\n  /* fexport:body-end */`;
  let out = source;
  const importRe = /\/\/ fexport:imports-start[\s\S]*?\/\/ fexport:imports-end\n/;
  if (importRe.test(out)) out = out.replace(importRe, () => importBlock);
  else {
    const all = [...out.matchAll(/^import [^;]*;[ \t]*\r?\n/gm)];
    const last = all[all.length - 1];
    const at = last ? last.index! + last[0].length : 0;
    out = out.slice(0, at) + importBlock + out.slice(at);
  }
  const bodyRe = /\/\* fexport:body-start \*\/[\s\S]*?\/\* fexport:body-end \*\//;
  if (bodyRe.test(out)) return out.replace(bodyRe, () => bodyBlock);
  const placeholder = /return <main data-page="[^"]*" \/>;/;
  if (!placeholder.test(out)) throw new Error('page file has neither the scaffold placeholder nor a generated body');
  return out.replace(placeholder, () => bodyBlock);
}

export async function loadFirstCmsItem(nextDir: string, collection: string): Promise<Record<string, any> | null> {
  const file = path.join(nextDir, 'src', 'content', `${collection}.ts`);
  try {
    const text = await readFile(file, 'utf8');
    const arrayStart = text.indexOf('[');
    if (arrayStart === -1) return null;
    const startIdx = text.indexOf('{', arrayStart);
    if (startIdx === -1) return null;
    let depth = 0;
    let endIdx = -1;
    let inString: string | null = null;
    let escape = false;
    for (let i = startIdx; i < text.length; i++) {
      const ch = text[i];
      if (inString) {
        if (escape) {
          escape = false;
        } else if (ch === '\\') {
          escape = true;
        } else if (ch === inString) {
          inString = null;
        }
      } else {
        if (ch === '"' || ch === "'" || ch === '`') {
          inString = ch;
        } else if (ch === '{') {
          depth++;
        } else if (ch === '}') {
          depth--;
          if (depth === 0) {
            endIdx = i;
            break;
          }
        }
      }
    }
    if (endIdx !== -1) {
      const objText = text.slice(startIdx, endIdx + 1);
      const fn = new Function(`return (${objText})`);
      return fn();
    }
  } catch {}
  return null;
}

async function settledAppear(
  page: Page,
  selectors: string[],
): Promise<Array<{ selector: string; opacity: string; transform: string }>> {
  if (!selectors.length) return [];
  const rows = (await page.evaluate(
    `((list) => list.map((selector) => {
      let el = null;
      try { el = document.querySelector(selector); } catch (e) {}
      if (!el) return null;
      const cs = getComputedStyle(el);
      return { selector, opacity: cs.opacity, transform: cs.transform };
    }))(${JSON.stringify(selectors)})`,
  )) as Array<{ selector: string; opacity: string; transform: string } | null>;
  return rows.filter((r): r is { selector: string; opacity: string; transform: string } => !!r);
}

interface RawPageData {
  page: PageInfo;
  slug: string;
  cssImports: string[];
  viewJsx: string;
  sections: SnapshotSection[];
  scriptDrawn: ScriptDrawn[];
}

export async function runGenerate(ctx: StageContext): Promise<GeneratedManifest> {
  const { nextDir, exportDir, state } = ctx;
  const analysis = path.join(nextDir, '.convert', 'analysis');
  const pages = await readJson<PageInfo[]>(path.join(analysis, 'pages.json'), []);
  const components = await readJson<ComponentInfo[]>(path.join(analysis, 'components.json'), []);
  const images = await readJson<Record<string, string>>(path.join(analysis, 'images.json'), {});
  const animations = await readJson<AnimationEntry[]>(path.join(analysis, 'animations.json'), []);
  const tokens = await readJson<Tokens>(path.join(analysis, 'tokens.json'), {
    colors: {},
    tokenMap: {},
    fonts: [],
    typeScale: [],
    breakpoints: { md: 810, lg: 1200 },
  });

  if (!pages.length) throw new Error('No analysis found: run the conversion stages first');

  for (const kind of ['misc', 'videos']) {
    const from = path.join(exportDir, 'assets', kind);
    const to = path.join(nextDir, 'public', kind);
    if ((await exists(from)) && !(await exists(to))) await cp(from, to, { recursive: true });
  }

  const cssDir = path.join(nextDir, 'src', 'styles', 'framer');
  const viewDir = path.join(nextDir, 'src', 'views');
  const sectionsDir = path.join(nextDir, 'src', 'sections');
  const shellDir = path.join(nextDir, 'src', 'components', 'shell');

  await mkdir(cssDir, { recursive: true });
  await mkdir(viewDir, { recursive: true });
  await mkdir(sectionsDir, { recursive: true });
  await mkdir(shellDir, { recursive: true });

  const pageRoutes: Record<string, string> = { 'index.html': '/' };
  for (const p of pages) {
    if (p.dynamic) {
      for (const m of p.dynamic.members) {
        pageRoutes[m.sourceFile] = p.route.replace('[slug]', m.slug);
      }
    } else {
      pageRoutes[p.sourceFile] = p.route;
    }
  }
  for (const [file, route] of Object.entries({ ...pageRoutes })) {
    const bare = path.posix.basename(file);
    if (bare !== file && !Object.hasOwn(pageRoutes, bare)) pageRoutes[bare] = route;
  }

  const rewrite = (s: string): string => {
    let out = rewriteTokens(s, tokens.tokenMap);
    out = rewriteAssets(out, images);
    out = rewriteLinks(out, pageRoutes);
    return out;
  };

  const writeCss = async (blocks: string[]): Promise<string[]> => {
    const imports: string[] = [];
    for (const block of blocks) {
      const css = rewrite(block);
      const name = createHash('sha1').update(css).digest('hex').slice(0, 10);
      await writeFile(path.join(cssDir, `${name}.css`), css, 'utf8');
      imports.push(`import '@/styles/framer/${name}.css';`);
    }
    return imports;
  };

  const motionAnchors: MotionAnchor[] = animations.map((entry, idx) => ({
    id: `m${idx + 1}`,
    route: entry.route,
    section: null,
    entry,
    matched: false,
  }));

  const warnings: string[] = [];
  const stubs: string[] = [];
  const scriptDrawnAll: ScriptDrawn[] = [];
  let scriptDrawnCounter = 0;
  const rawPages: RawPageData[] = [];

  const generateStart = Date.now();
  let pagesMs = 0;
  const server = await startExportServer(exportDir);
  let browser: Browser | undefined;

  try {
    browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox'] });
    const live = await browser.newPage();
    await live.setViewport({ width: 1440, height: 900 });
    const still = await browser.newPage();
    await still.setJavaScriptEnabled(false);

    for (const p of pages) {
      const pageStart = Date.now();
      const slug = routeSlug(p.route);
      const sourceFile = p.dynamic ? p.dynamic.members[0].sourceFile : p.sourceFile;
      const html = await readFile(path.join(exportDir, sourceFile), 'utf8');
      const sections = sectionsWithFallback(pageSections(html));
      const pageUrl = server.url + (sourceFile === 'index.html' ? '/' : '/' + sourceFile);

      // Live load: appear states + visible items
      await live.goto(pageUrl, { waitUntil: 'load', timeout: 60_000 });
      await settleExport(live);
      const appearSelectors = ssrAppearCandidates(html).map((c) => c.selector);
      const appear = await settledAppear(live, appearSelectors);
      const liveVisible = (await live.evaluate(
        `(${VISIBLE_ITEMS_SRC})(${JSON.stringify(sections)})`,
      )) as VisibleItem[];

      // Wait 2 s for ticking script-drawn items
      await new Promise((r) => setTimeout(r, 2000));
      const liveLaterVisible = (await live.evaluate(
        `(${VISIBLE_ITEMS_SRC})(${JSON.stringify(sections)})`,
      )) as VisibleItem[];

      // Still load
      await still.goto(pageUrl, { waitUntil: 'domcontentloaded', timeout: 60_000 });
      const stillVisible = (await still.evaluate(
        `(${VISIBLE_ITEMS_SRC})(${JSON.stringify(sections)})`,
      )) as VisibleItem[];

      // Diff script drawn
      // ids are unique over the whole site (s1, s2, ... continuing across pages)
      const pageScriptDrawn = diffScriptDrawn(p.route, liveVisible, stillVisible, liveLaterVisible).map((sd) => ({
        ...sd,
        id: `s${++scriptDrawnCounter}`,
      }));
      scriptDrawnAll.push(...pageScriptDrawn);

      // Hidden class map
      const allStyles = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)].map((m) => m[1]).join('\n');
      const hiddenMap = hiddenClassMap(allStyles, tokens.breakpoints);

      // Motion entries for this page
      const pageMotion = motionAnchors
        .filter((m) => m.route === p.route)
        .map((m) => ({ id: m.id, selector: m.entry.selector }));

      // CMS entries for this page (if dynamic)
      const cmsEntries: Array<{ field: string; value: string }> = [];
      if (p.dynamic) {
        const firstItem = await loadFirstCmsItem(nextDir, p.dynamic.collection);
        if (firstItem) {
          for (const [k, v] of Object.entries(firstItem)) {
            if (typeof v === 'string' && v.trim()) {
              cmsEntries.push({ field: k, value: v.trim() });
            }
          }
        }
      }

      const plan: SnapshotPlan = {
        sections: sections.map((s) => ({ name: s.name, selector: s.selector })),
        appear,
        hiddenMap,
        motion: pageMotion,
        cms: cmsEntries,
        components: components.map((c) => ({
          name: c.name,
          selector: c.selector || `[data-framer-name="${c.name}"]`,
        })),
        scriptDrawn: pageScriptDrawn.map((sd) => ({
          id: sd.id,
          section: sd.section,
          x: sd.box.x,
          y: sd.box.y,
        })),
        emptyBytes: 1000,
        oversizedBytes: 120000,
      };

      const snap = (await still.evaluate(snapshotScript(plan))) as SnapshotOut | null;
      if (!snap) throw new Error(`${sourceFile} has no #main element`);

      // Collect stubs
      for (const stub of snap.stubs || []) {
        const sectionName = stub.section || 'main';
        stubs.push(`${p.route} · ${sectionName} · ${stub.kind}`);
      }

      // Update motion matching and emit warnings
      for (const anchor of motionAnchors.filter((m) => m.route === p.route)) {
        if (snap.unmatchedMotion && snap.unmatchedMotion.includes(anchor.id)) {
          anchor.matched = false;
          anchor.section = null;
          const msg = `generate: motion anchor not found (${anchor.id}: ${anchor.entry.selector} on ${p.route})`;
          warnings.push(msg);
          ctx.log(msg);
        } else {
          anchor.matched = true;
          const sec = snap.sections.find((s) => s.motion.includes(anchor.id));
          anchor.section = sec ? sec.name : null;
        }
      }

      const cssImports = await writeCss(snap.css);

      rawPages.push({
        page: p,
        slug,
        cssImports,
        viewJsx: snap.viewJsx,
        sections: snap.sections,
        scriptDrawn: pageScriptDrawn,
      });

      const pageMs = Date.now() - pageStart;
      pagesMs += pageMs;
      ctx.log(`generate: page ${p.route}${p.dynamic ? ' (dynamic)' : ''}`);
    }
  } finally {
    await browser?.close().catch(() => {});
    await server.stop().catch(() => {});
  }

  // Shell detection across all pages
  const shellInput = rawPages.map((rp) => ({
    route: rp.page.route,
    sections: rp.sections.filter((s) => !s.empty).map((s) => ({ name: s.name, jsx: s.jsx })),
  }));
  const shellCandidates = findShellSections(shellInput);

  const shellTaken = new Set<string>();
  const manifestShell: GeneratedShell[] = [];
  const shellByName = new Map<string, { candidate: ShellCandidate; component: string; file: string }>();

  for (const candidate of shellCandidates) {
    const comp = componentName(candidate.name, shellTaken);
    const relFile = `src/components/shell/${comp}.tsx`;
    const absFile = path.join(nextDir, relFile);

    const firstPage = rawPages.find((rp) => candidate.pages.includes(rp.page.route));
    const firstSec = firstPage?.sections.find((s) => s.name === candidate.name);
    let rawJsx = firstSec ? firstSec.jsx : '';
    let rewrittenJsx = rewrite(rawJsx);

    if (!rewrittenJsx.includes(`data-section="${candidate.name}"`)) {
      rewrittenJsx = rewrittenJsx.replace(/^<([A-Za-z0-9_-]+)/, `<$1 data-section="${candidate.name}"`);
    }

    await mkdir(path.dirname(absFile), { recursive: true });
    await writeFile(
      absFile,
      `${FILE_HEADER}export default function ${comp}({ item }: { item?: any } = {}) {\n  return (\n${rewrittenJsx}\n  );\n}\n`,
      'utf8',
    );

    manifestShell.push({
      name: candidate.name,
      component: comp,
      file: relFile,
      pages: candidate.pages,
      differences: candidate.differences,
    });
    shellByName.set(candidate.name, { candidate, component: comp, file: relFile });
    ctx.log(`generate: shell component ${comp} (${candidate.pages.length} pages)`);
  }

  // Write Sections, Views, and Page Patches
  const manifestPages: GeneratedPage[] = [];

  for (const rp of rawPages) {
    const pageSectionsList: GeneratedSection[] = [];
    const pageInline: string[] = [];
    const pageShellNames: string[] = [];
    const pageTaken = new Set<string>();
    const sectionComponentByName = new Map<string, { component: string; isShell: boolean }>();

    for (const s of rp.sections) {
      if (s.empty) {
        pageInline.push(s.name);
        continue;
      }

      const shellInfo = shellByName.get(s.name);
      if (shellInfo && shellInfo.candidate.pages.includes(rp.page.route)) {
        pageShellNames.push(s.name);
        sectionComponentByName.set(s.name, { component: shellInfo.component, isShell: true });
        continue;
      }

      const comp = componentName(s.name, pageTaken);
      const relFile = `src/sections/${rp.slug}/${comp}.tsx`;
      const absFile = path.join(nextDir, relFile);
      await mkdir(path.dirname(absFile), { recursive: true });

      // Handle parts for oversized sections
      const partRecords: GeneratedPart[] = [];
      const partImports: string[] = [];
      let sectionJsx = s.jsx;
      const partTaken = new Set<string>();

      for (const part of s.parts) {
        const partComp = componentName(part.name, partTaken);
        const partRelFile = `src/sections/${rp.slug}/${comp}/${partComp}.tsx`;
        const partAbsFile = path.join(nextDir, partRelFile);
        await mkdir(path.dirname(partAbsFile), { recursive: true });
        await writeFile(
          partAbsFile,
          `${FILE_HEADER}export default function ${partComp}({ item }: { item?: any } = {}) {\n  return (\n${rewrite(part.jsx)}\n  );\n}\n`,
          'utf8',
        );
        partRecords.push({
          name: part.name,
          component: partComp,
          file: partRelFile,
          motion: part.motion,
          scriptDrawn: part.scriptDrawn,
          hasVariants: part.hasVariants,
          repeated: part.repeated,
          cmsFields: part.cmsFields,
        });
        partImports.push(`import ${partComp} from './${comp}/${partComp}';`);

        const partRe = new RegExp(
          `<fexport-part\\b[^>]*\\bdata-name="${escapeRegex(part.name)}"[^>]*(?:\\/>|>(?:[\\s\\S]*?<\\/fexport-part>)?)`,
          'g',
        );
        sectionJsx = sectionJsx.replace(partRe, `<${partComp} item={item} />`);
      }

      let rewrittenSectionJsx = rewrite(sectionJsx);
      if (!rewrittenSectionJsx.includes(`data-section="${s.name}"`)) {
        rewrittenSectionJsx = rewrittenSectionJsx.replace(/^<([A-Za-z0-9_-]+)/, `<$1 data-section="${s.name}"`);
      }

      const partHeader = partImports.length ? `${partImports.join('\n')}\n\n` : '';
      await writeFile(
        absFile,
        `${FILE_HEADER}${partHeader}export default function ${comp}({ item }: { item?: any } = {}) {\n  return (\n${rewrittenSectionJsx}\n  );\n}\n`,
        'utf8',
      );

      // With parts, the section keeps only the items that no part claims.
      const inParts = new Set(partRecords.flatMap((pr) => pr.scriptDrawn ?? []));
      const secScriptDrawn = rp.scriptDrawn
        .filter((sd) => sd.section === s.name && !inParts.has(sd.id))
        .map((sd) => sd.id);
      pageSectionsList.push({
        name: s.name,
        component: comp,
        file: relFile,
        parts: partRecords,
        motion: s.motion,
        scriptDrawn: secScriptDrawn,
        hasVariants: s.hasVariants,
        repeated: s.repeated,
        cmsFields: s.cmsFields,
      });
      sectionComponentByName.set(s.name, { component: comp, isShell: false });
    }

    // Replace fexport-section placeholders in viewJsx
    let viewBody = rp.viewJsx;
    for (const [secName, info] of sectionComponentByName) {
      const secRe = new RegExp(
        `<fexport-section\\b[^>]*\\bdata-name="${escapeRegex(secName)}"[^>]*(?:\\/>|>(?:[\\s\\S]*?<\\/fexport-section>)?)`,
        'g',
      );
      viewBody = viewBody.replace(secRe, `<${info.component} item={item} />`);
    }

    // View component imports in manifest order (in order of non-empty sections)
    const componentImports: string[] = [];
    for (const s of rp.sections) {
      if (s.empty) continue;
      const info = sectionComponentByName.get(s.name);
      if (!info) continue;
      if (info.isShell) {
        componentImports.push(`import ${info.component} from '@/components/shell/${info.component}';`);
      } else {
        componentImports.push(`import ${info.component} from '@/sections/${rp.slug}/${info.component}';`);
      }
    }

    const viewRelFile = `src/views/${rp.slug}.tsx`;
    const viewAbsFile = path.join(nextDir, viewRelFile);
    await mkdir(path.dirname(viewAbsFile), { recursive: true });

    const cssHeader = rp.cssImports.length ? `${rp.cssImports.join('\n')}\n\n` : '';
    const compHeader = componentImports.length ? `${componentImports.join('\n')}\n\n` : '';

    await writeFile(
      viewAbsFile,
      `${FILE_HEADER}${cssHeader}${compHeader}export default function View({ item }: { item?: any } = {}) {\n  return (\n${rewrite(viewBody)}\n  );\n}\n`,
      'utf8',
    );

    // Patch page file
    const pageFile = path.join(
      nextDir,
      rp.page.route === '/' ? 'src/app/page.tsx' : `src/app/${rp.page.route.replace(/^\//, '')}/page.tsx`,
    );
    if (await exists(pageFile)) {
      const pageSource = await readFile(pageFile, 'utf8');
      const patched = rp.page.dynamic
        ? patchPage(pageSource, `import View from '@/views/${rp.slug}';`, 'return <View item={item} />;')
        : patchPage(pageSource, `import View from '@/views/${rp.slug}';`, 'return <View />;');
      await writeFile(pageFile, patched, 'utf8');
    }

    manifestPages.push({
      route: rp.page.route,
      slug: rp.slug,
      view: viewRelFile,
      ...(rp.page.dynamic
        ? {
            dynamic: {
              collection: rp.page.dynamic.collection,
              firstSlug: rp.page.dynamic.members[0].slug,
            },
          }
        : {}),
      sections: pageSectionsList,
      inline: pageInline,
      shell: pageShellNames,
    });
  }

  const manifest: GeneratedManifest = {
    version: 1,
    pages: manifestPages,
    shell: manifestShell,
    motion: motionAnchors,
    scriptDrawn: scriptDrawnAll,
    stubs,
    warnings,
  };

  await writeManifest(nextDir, manifest);
  state.stages.generate = 'done';
  addTime(state, 'setup', Math.max(0, Date.now() - generateStart - pagesMs));
  await saveState(state);

  return manifest;
}
