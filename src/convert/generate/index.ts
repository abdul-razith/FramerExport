import { startExportServer } from '../verify/serve.js';
import { DOM_TO_JSX_SRC, rewriteAssets, rewriteLinks } from './dom-to-jsx.js';

export interface GenerateResult {
  pages: string[];
  components: string[];
  /** Task ids left alone because they are already done (for example built by an AI agent). */
  skipped: string[];
}

const FILE_HEADER = '// @ts-nocheck\n/* eslint-disable */\n// Generated by `fexport convert generate`. Safe to edit by hand.\n';

const exists = (p: string): Promise<boolean> => stat(p).then(() => true, () => false);

async function readJson<T>(file: string, fallback: T): Promise<T> {
  try {
    return JSON.parse(await readFile(file, 'utf8')) as T;
  } catch {
    return fallback;
  }
}

const fileSafe = (s: string): string => s.replace(/[^A-Za-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '') || 'item';
const identifier = (s: string): string => {
  const id = s.replace(/[^A-Za-z0-9_$]/g, '');
  return /^[0-9]/.test(id) || !id ? `_${id}` : id;
};

/** Inserts the generated imports and view body into a scaffolded page file; safe to run again. */
export function patchPage(source: string, imports: string, body: string): string {
  const importBlock = `// fexport:imports-start\n${imports}\n// fexport:imports-end\n`;
  const bodyBlock = `/* fexport:body-start */\n  ${body}\n  /* fexport:body-end */`;
  let out = source;
  const importRe = /\/\/ fexport:imports-start[\s\S]*?\/\/ fexport:imports-end\n/;
  if (importRe.test(out)) out = out.replace(importRe, () => importBlock);
  else {
    const all = [...out.matchAll(/^import [^;]*;[ \t]*\r?\n/gm)];
    const last = all[all.length - 1];
    const at = last ? last.index! + last[0].length : 0;
    out = out.slice(0, at) + importBlock + out.slice(at);
  }
  const bodyRe = /\/\* fexport:body-start \*\/[\s\S]*?\/\* fexport:body-end \*\//;
  if (bodyRe.test(out)) return out.replace(bodyRe, () => bodyBlock);
  const placeholder = /return <main data-page="[^"]*" \/>;/;
  if (!placeholder.test(out)) throw new Error('page file has neither the scaffold placeholder nor a generated body');
  return out.replace(placeholder, () => bodyBlock);
}

interface Snapshot {
  jsx: string;
  css: string[];
}

interface Item {
  /** File name of the view (without extension). */
  view: string;
  sourceFile: string;
  slug?: string;
}

function buildPlan(sections: Array<{ name: string; selector: string }>, appear: Array<{ selector: string; opacity: string; transform: string }>): string {
  return JSON.stringify({ sections, appear });
}

/** Runs inside the page with JavaScript disabled: applies settled appear states, marks sections, converts #main. */
function snapshotScript(plan: string): string {
  return `(function (plan) {
    var conv = ${DOM_TO_JSX_SRC};
    var main = document.querySelector('#main');
    if (!main) return null;
    plan.appear.forEach(function (a) {
      var el = document.querySelector(a.selector);
      if (!el) return;
      el.style.opacity = a.opacity;
      if (a.transform === 'none') el.style.removeProperty('transform');
      else el.style.transform = a.transform;
    });
    plan.sections.forEach(function (s) {
      var el = null;
      try { el = document.querySelector(s.selector); } catch (e) {}
      if (el) el.setAttribute('data-section', s.name);
    });
    Array.prototype.slice.call(main.querySelectorAll('style')).forEach(function (s) {
      if ((s.textContent || '').indexOf('#__framer-editorbar') === 0) s.remove();
    });
    var css = Array.prototype.slice.call(document.head.querySelectorAll('style'))
      .filter(function (s) { return !s.hasAttribute('data-framer-font-css'); })
      .map(function (s) { return s.textContent || ''; })
      .filter(Boolean);
    return { jsx: conv.element(main), css: css };
  })(${plan})`;
}

async function settledAppear(
  page: Page,
  url: string,
  selectors: string[],
): Promise<Array<{ selector: string; opacity: string; transform: string }>> {
  if (!selectors.length) return [];
  await page.goto(url, { waitUntil: 'load', timeout: 60_000 });
  await settleExport(page);
  const rows = (await page.evaluate(
    `((list) => list.map((selector) => {
      let el = null;
      try { el = document.querySelector(selector); } catch (e) {}
      if (!el) return null;
      const cs = getComputedStyle(el);
      return { selector, opacity: cs.opacity, transform: cs.transform };
    }))(${JSON.stringify(selectors)})`,
  )) as Array<{ selector: string; opacity: string; transform: string } | null>;
  return rows.filter((r): r is { selector: string; opacity: string; transform: string } => !!r);
}

export async function runGenerate(ctx: StageContext): Promise<GenerateResult> {
  const { nextDir, exportDir, state } = ctx;
  const analysis = path.join(nextDir, '.convert', 'analysis');
  const pages = await readJson<PageInfo[]>(path.join(analysis, 'pages.json'), []);
  const components = await readJson<ComponentInfo[]>(path.join(analysis, 'components.json'), []);
  const images = await readJson<Record<string, string>>(path.join(analysis, 'images.json'), {});
  if (!pages.length) throw new Error('No analysis found: run the conversion stages first');

  for (const kind of ['misc', 'videos']) {
    const from = path.join(exportDir, 'assets', kind);
    const to = path.join(nextDir, 'public', kind);
    if ((await exists(from)) && !(await exists(to))) await cp(from, to, { recursive: true });
  }

  const cssDir = path.join(nextDir, 'src', 'styles', 'framer');
  const viewDir = path.join(nextDir, 'src', 'views');
  await mkdir(cssDir, { recursive: true });
  await mkdir(viewDir, { recursive: true });
  const pageRoutes: Record<string, string> = { 'index.html': '/' };
  for (const p of pages) {
    if (p.dynamic) for (const m of p.dynamic.members) pageRoutes[m.sourceFile] = p.route.replace('[slug]', m.slug);
    else pageRoutes[p.sourceFile] = p.route;
  }
  // Pages inside subpages/ link to each other by bare file name (`about.html`).
  for (const [file, route] of Object.entries({ ...pageRoutes })) {
    const bare = path.posix.basename(file);
    if (bare !== file && !Object.hasOwn(pageRoutes, bare)) pageRoutes[bare] = route;
  }
  const rewrite = (s: string): string => rewriteLinks(rewriteAssets(s, images), pageRoutes);
  const writeCss = async (blocks: string[]): Promise<string[]> => {
    const imports: string[] = [];
    for (const block of blocks) {
      const css = rewrite(block);
      const name = createHash('sha1').update(css).digest('hex').slice(0, 10);
      await writeFile(path.join(cssDir, `${name}.css`), css, 'utf8');
      imports.push(`import '@/styles/framer/${name}.css';`);
    }
    return imports;
  };

  const result: GenerateResult = { pages: [], components: [], skipped: [] };
  const server = await startExportServer(exportDir);
  let browser: Browser | undefined;
  try {
    browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox'] });
    const live = await browser.newPage();
    await live.setViewport({ width: 1440, height: 900 });
    const still = await browser.newPage();
    await still.setJavaScriptEnabled(false);

    const snapshot = async (sourceFile: string): Promise<Snapshot> => {
      const html = await readFile(path.join(exportDir, sourceFile), 'utf8');
      const url = server.url + (sourceFile === 'index.html' ? '/' : '/' + sourceFile);
      const appear = await settledAppear(live, url, ssrAppearCandidates(html).map((c) => c.selector));
      await still.goto(url, { waitUntil: 'domcontentloaded', timeout: 60_000 });
      const sections = sectionsWithFallback(pageSections(html));
      const out = (await still.evaluate(snapshotScript(buildPlan(sections, appear)))) as Snapshot | null;
      if (!out) throw new Error(`${sourceFile} has no #main element`);
      return out;
    };

    for (const p of pages) {
      const task = Object.values(state.tasks).find((t) => t.kind === 'page' && t.route === p.route);
      const pageFile = path.join(nextDir, p.route === '/' ? 'src/app/page.tsx' : `src/app/${p.route.replace(/^\//, '')}/page.tsx`);
      if (task?.status === 'done') {
        result.skipped.push(task.id);
        continue;
      }
      const base = fileSafe(routeSlug(p.route));
      const items: Item[] = p.dynamic
        ? p.dynamic.members.map((m) => ({ view: `${base}/${fileSafe(m.slug)}`, sourceFile: m.sourceFile, slug: m.slug }))
        : [{ view: base, sourceFile: p.sourceFile }];
      for (const item of items) {
        const snap = await snapshot(item.sourceFile);
        const cssImports = await writeCss(snap.css);
        const viewFile = path.join(viewDir, `${item.view}.tsx`);
        await mkdir(path.dirname(viewFile), { recursive: true });
        await writeFile(
          viewFile,
          `${FILE_HEADER}${cssImports.join('\n')}\n\nexport default function View() {\n  return (\n${rewrite(snap.jsx)}\n  );\n}\n`,
          'utf8',
        );
      }
      const source = await readFile(pageFile, 'utf8');
      const patched = p.dynamic
        ? patchPage(
            source,
            `import type { ComponentType } from 'react';\nconst VIEWS: Record<string, () => Promise<{ default: ComponentType }>> = {\n${items
              .map((i) => `  ${JSON.stringify(i.slug)}: () => import('@/views/${i.view}'),`)
              .join('\n')}\n};`,
            'const load = Object.hasOwn(VIEWS, slug) ? VIEWS[slug] : undefined;\n  if (!load) notFound();\n  const { default: View } = await load();\n  return <View />;',
          )
        : patchPage(source, `import View from '@/views/${base}';`, 'return <View />;');
      await writeFile(pageFile, patched, 'utf8');
      result.pages.push(p.route);
      ctx.log(`generate: page ${p.route}${p.dynamic ? ` (${items.length} items)` : ''}`);
    }

    const sliceTab = still;
    for (const c of components) {
      const task = Object.values(state.tasks).find((t) => t.kind === 'component' && t.targets.includes(`src/components/${c.name}.tsx`));
      if (task?.status === 'done') {
        result.skipped.push(task.id);
        continue;
      }
      const slice = await readFile(path.join(nextDir, c.slice), 'utf8');
      await sliceTab.setContent(`<!doctype html><html><head></head><body>${slice}</body></html>`);
      const parts = (await sliceTab.evaluate(
        `(function () { var conv = ${DOM_TO_JSX_SRC}; return conv.children(document.body); })()`,
      )) as string[];
      const file = path.join(nextDir, 'src', 'components', `${c.name}.tsx`);
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(
        file,
        `${FILE_HEADER}\nexport function ${identifier(c.name)}() {\n  return (\n    <>\n${rewrite(parts.join('\n'))}\n    </>\n  );\n}\n`,
        'utf8',
      );
      result.components.push(c.name);
    }
    ctx.log(`generate: ${result.components.length} component(s)`);
  } finally {
    await browser?.close().catch(() => {});
    await server.stop().catch(() => {});
  }
  await saveState(state);
  return result;
}
