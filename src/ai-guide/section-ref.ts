import type { Breakpoint } from '../nextjs/model.js';
import type { MarkupCopy } from './export-markup.js';
import { describeAnimation, type ExportAnimation } from './export-motion.js';
import type { InteractionState } from './interactions.js';
import { motionLine } from './motion.js';
import { slugify } from './outline.js';
import type { WidthKey } from './sections-json.js';
import type { GuidePage, GuideSection, MotionEntry } from './types.js';

export interface SectionRefInput {
  page: GuidePage;
  section: GuideSection;
  exportFile: string;
  markup: MarkupCopy[] | Error;
  css: string | Error;
  /** Text style presets the markup uses (their rules are in ai-guide/text-styles.css). */
  presets?: string[];
  animations: ExportAnimation[] | Error;
  recorded: MotionEntry[];
  states: InteractionState[];
  /** Screenshot slices per width, file names inside the section folder. */
  slices: Partial<Record<WidthKey, string[]>>;
}

const WIDTH_NAME: Record<Breakpoint, string> = { base: 'desktop', tablet: 'tablet', mobile: 'mobile' };
const ALL = 'base,tablet,mobile';
const widthLabel = (w: Breakpoint[]) => w.map((bp) => WIDTH_NAME[bp]).join(', ');
const notAvailable = (e: Error) => `not available: ${e.message}`;

/** `03-feature-works`; shell parts `S1-header`. */
export function sectionDirName(s: GuideSection): string {
  return `${s.id}-${slugify(s.name)}`;
}

/** `markup.html` when every width shows the same markup, else one file per copy (`markup.tablet-mobile.html`). */
export function markupFileNames(copies: MarkupCopy[]): string[] {
  if (copies.length === 1) return ['markup.html'];
  return copies.map((c) => `markup.${c.widths.map((bp) => WIDTH_NAME[bp]).join('-')}.html`);
}

const size = (b?: { w: number; h: number }) => (b ? `${Math.round(b.w)}×${Math.round(b.h)}` : '—');

/** The section's `ref.md`: the AI's entry point for building it from the export's own code. */
export function renderSectionRef(input: SectionRefInput): string {
  const { page, section: s, exportFile } = input;
  const out: string[] = [`# ${s.id} ${s.name} — ${page.route}`, ''];
  if (s.parent) out.push(`Part of the section "${s.parent}" (split because it is very tall).`, '');
  if (s.generic) out.push('The Framer layer name is generic: choose a meaningful component name.', '');

  out.push('## Where', '');
  const element = [s.framerName ? `data-framer-name="${s.framerName}"` : '', s.className ? `class="${s.className}"` : ''].filter(Boolean).join(', ');
  if (input.markup instanceof Error) out.push(`- Export file: \`${exportFile}\`${element ? `, element ${element}` : ''}. markup: ${notAvailable(input.markup)}`);
  else {
    const lines = input.markup.map((c) => `line ${c.line}`).filter((v, i, a) => a.indexOf(v) === i).join(', ');
    out.push(`- Export file: \`${exportFile}\`, ${lines}${element ? `, element ${element}` : ''}.`);
  }
  out.push(`- Size: desktop ${size(s.boxes.base)}, tablet ${size(s.boxes.tablet)}, mobile ${size(s.boxes.mobile)}.`);
  const slices = (Object.entries(input.slices) as [WidthKey, string[]][]).filter(([, f]) => f.length);
  if (slices.length) out.push(`- Screenshots (900px slices): ${slices.map(([w, f]) => `${w}: ${f.map((x) => `\`${x}\``).join(', ')}`).join(' · ')}.`);
  out.push('');

  out.push('## Widths', '');
  if (!(input.markup instanceof Error)) {
    const names = markupFileNames(input.markup);
    input.markup.forEach((c, i) => out.push(`- \`${names[i]}\`: ${c.widths.join(',') === ALL ? 'all widths' : widthLabel(c.widths)}`));
  }
  const partial = Object.entries(s.widthsOf).filter(([, w]) => w.join(',') !== ALL);
  if (partial.length) {
    out.push('', 'Shown only at some widths:');
    for (const [item, w] of partial) out.push(`- "${item}" (${widthLabel(w)})`);
  } else out.push('', 'Everything in this section is shown at every width.');
  out.push('');

  out.push('## Content', '');
  const tag = (key: string) => {
    const w = s.widthsOf[key];
    return w && w.join(',') !== ALL ? ` (${widthLabel(w)})` : '';
  };
  if (s.texts.length) out.push('Text:', ...s.texts.map((t) => `- "${t}"${tag(t)}`), '');
  if (s.images.length) {
    out.push('Images:', ...s.images.map((i) => `- \`${i.exportPath}\` → \`public${i.suggested}\` (${i.width}×${i.height}${i.alt ? `, alt "${i.alt}"` : ''})${tag(i.exportPath)}`), '');
  }
  if (s.links.length) out.push('Links:', ...s.links.map((l) => `- "${l.text}" → ${l.href}${tag(l.href)}`), '');
  if (s.generated.length) {
    out.push('Generated by the page (not content — build them as small components and mark the element `data-live`):');
    out.push(...s.generated.map((g) => `- generated (${g.kind}), e.g. "${g.text}"`), '');
  }
  if (s.decorations.length) out.push('Decoration:', ...s.decorations.map((d) => `- ${d} (generate it, do not list it as content)`), '');
  if (!s.texts.length && !s.images.length && !s.links.length && !s.generated.length && !s.decorations.length) out.push('No text, images or links.', '');

  out.push('## Animations', '');
  if (input.animations instanceof Error) out.push(`Framer settings: ${notAvailable(input.animations)}`);
  else if (!input.animations.length) out.push('No Framer animation settings for this section.');
  else {
    out.push("Framer's own settings, read from the export's JS (exact values):");
    out.push(...input.animations.map((a) => `- ${a.layer ? `**${a.layer}** (\`${a.className}\`)` : `\`${a.className}\``} — ${describeAnimation(a)}`));
  }
  if (input.recorded.length) out.push('', 'Recorded on the live site (frames in the page folder):', ...input.recorded.map(motionLine));
  out.push('');

  out.push('## Interactive', '');
  if (!input.states.length) out.push('No hover or click changes found.');
  else out.push(...input.states.map((st) => `- ${st.element} (${st.action}): \`${st.before}\` → \`${st.after}\``));
  out.push('');

  out.push('## Build', '');
  out.push(
    `Build from \`markup.*.html\` + \`styles.css\`: keep the element structure, convert the CSS to Tailwind with exact values, colours and fonts from tokens; put \`data-section="${s.id}"\` on the root and \`data-live\` on generated elements.`
  );
  if (input.css instanceof Error) out.push('', `styles.css: ${notAvailable(input.css)}`);
  if (input.presets?.length) out.push('', `Text styles used (rules in \`ai-guide/text-styles.css\`): ${input.presets.map((p) => `\`${p}\``).join(', ')}.`);
  out.push('');
  return out.join('\n');
}
